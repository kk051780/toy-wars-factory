"""Deterministic original TRAP RAIDERS S1 architecture plan generator.
Creates *only* non-interactive visual geometry; no game authority or Roblox access.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

STYLES = {"STONE", "COPPER", "RED", "BLUE", "DARK"}
VALID_KEYS = {"id", "center", "size", "style"}
MAX_PARTS = 80


def make_spec() -> dict:
    elements: list[dict] = []
    def add(name: str, x: float, y: float, z: float, sx: float, sy: float, sz: float, style: str) -> None:
        assert style in STYLES
        elements.append({"id": name, "center": [x, y, z], "size": [sx, sy, sz], "style": style})

    for team, sign, color in [("RED", -1, "RED"), ("BLUE", 1, "BLUE")]:
        # Existing map: back wall at x= +/-123, z=0; each tooth sits ABOVE the real wall.
        for z in [-39, -26, -13, 0, 13, 26, 39]:
            add(f"{team}_WALL_TOOTH_{z:+03d}", sign * 123, 17.2, z, 5, 5, 5.5, "STONE")
        # Existing solid towers at x= +/-115, z= +/-35. Rooftops never change collisions.
        for suffix, z in [("N", -35), ("S", 35)]:
            add(f"{team}_{suffix}_ROOF_PLATE", sign * 115, 19.9, z, 13, 1.8, 13, color)
            add(f"{team}_{suffix}_ROOF_INSET", sign * 115, 21.5, z, 9, 1.4, 9, "DARK")
            add(f"{team}_{suffix}_ROOF_CROWN", sign * 115, 24, z, 3, 3.8, 3, "COPPER")
        # The core is the existing solid gameplay part; crown is only a visual shell above it.
        add(f"{team}_CORE_CROWN", sign * 107, 14, 0, 12, 2.2, 12, color)
        for dx, dz in [(-4.4, -4.4), (-4.4, 4.4), (4.4, -4.4), (4.4, 4.4)]:
            add(f"{team}_CORE_FINIAL_{dx:+.0f}_{dz:+.0f}", sign * (107 + dx), 17, dz,
                2.2, 4.2, 2.2, "COPPER")
        # Existing solid long wall locations at x= +/-103, z= +/-44.
        for suffix, z in [("N", -44), ("S", 44)]:
            add(f"{team}_{suffix}_PARAPET", sign * 103, 15, z, 40, 2, 5, "DARK")
    # Above real arena side boundary wall near z +/-71, decorative midpoint landmark only.
    for suffix, z in [("N", -71), ("S", 71)]:
        for x in [-24, -12, 12, 24]:
            add(f"MID_{suffix}_TOOTH_{x:+03d}", x, 17, z, 5, 4, 4, "STONE")
        add(f"MID_{suffix}_CAP", 0, 17.8, z, 8, 6, 4.5, "COPPER")
    return {"schema": "TRAP_RAIDERS_S1_ARCHITECTURE_V1", "part_budget": MAX_PARTS,
            "collision": False, "source_map": "TRAP_RAIDERS_S1", "elements": elements}


def validate(doc: dict) -> None:
    assert set(doc) == {"schema", "part_budget", "collision", "source_map", "elements"}
    assert doc["schema"] == "TRAP_RAIDERS_S1_ARCHITECTURE_V1"
    assert doc["source_map"] == "TRAP_RAIDERS_S1"
    assert doc["collision"] is False
    assert doc["part_budget"] == MAX_PARTS
    assert isinstance(doc["elements"], list) and 0 < len(doc["elements"]) <= MAX_PARTS
    used = set()
    for e in doc["elements"]:
        assert isinstance(e, dict) and set(e) == VALID_KEYS
        name = e["id"]
        assert isinstance(name, str) and name.startswith(("RED_", "BLUE_", "MID_"))
        assert name not in used
        used.add(name)
        assert e["style"] in STYLES
        for k in ("center", "size"):
            assert isinstance(e[k], list) and len(e[k]) == 3
            assert all(isinstance(v, (int, float)) and not isinstance(v, bool) and abs(v) < 1e6 for v in e[k])
        x,y,z=e["center"]
        sx,sy,sz=e["size"]
        assert all(0.1 <= v <= 50 for v in (sx,sy,sz))
        assert abs(x) + sx / 2 <= 129
        assert abs(z) + sz / 2 <= 75
        assert 0 <= y - sy / 2 < y + sy / 2 <= 32


def plan_luau(doc: dict) -> str:
    validate(doc)
    lines = ["--!strict", "-- GENERATED by tools/generate_architecture.py from assets/architecture_spec.json.",
             "-- Deterministic visual-only geometry. DO NOT edit by hand; regenerate and test.", "return {"]
    for e in doc["elements"]:
        pos=", ".join(str(v) for v in e["center"])
        size=", ".join(str(v) for v in e["size"])
        lines.append(f'    {{id = "{e["id"]}", center = {{{pos}}}, size = {{{size}}}, style = "{e["style"]}"}},')
    lines.append("}")
    return "\n".join(lines)+"\n"


def main() -> None:
    root=Path(__file__).resolve().parents[1]
    parser=argparse.ArgumentParser()
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args()
    spec=make_spec()
    validate(spec)
    spec_text=json.dumps(spec,ensure_ascii=False,sort_keys=True,indent=2)+"\n"
    out_spec=root/"assets"/"architecture_spec.json"
    out_luau=root/"src"/"CastleArchitecturePlan.luau"
    luau_text=plan_luau(spec)
    if args.check:
        assert out_spec.read_text(encoding="utf-8")==spec_text, "spec drift"
        assert out_luau.read_text(encoding="utf-8")==luau_text, "generated Luau drift"
        print("PASS reproducible architecture plan",len(spec["elements"]))
    else:
        out_spec.write_text(spec_text,encoding="utf-8")
        out_luau.write_text(luau_text,encoding="utf-8")
        print("generated",len(spec["elements"]),"visual-only parts")

if __name__=="__main__": main()
