#!/usr/bin/env python3
"""Actual original #275 Luau source executed in real native Luau interpreter.

Claims ONLY policy execution, not Roblox engine, DataStore persistence or Android.
Original source byte exact; tests include free hatch once per match and next-match
permission after server-only equip. No actual published odds/shop.
"""
from pathlib import Path
import argparse,hashlib
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/"inputs/RewardEquipRules.luau"
EXPECTED="0edf0993e41785b1e206b6ad09955a9984a346e5"
b=SOURCE.read_bytes()
blob=hashlib.sha1(b"blob "+str(len(b)).encode()+b"\0"+b).hexdigest()
assert blob==EXPECTED,(blob,EXPECTED)
p=argparse.ArgumentParser()
p.add_argument("--write",required=True,type=Path)
args=p.parse_args()
tests=r'''
local R=(function()
'''+b.decode("utf-8")+r'''
end)()
local tests=0
local function check(actual,expected,label)
 tests+=1
 assert(actual==expected,label.." expected="..tostring(expected).." got="..tostring(actual))
end
local state=R.new()
check(state.phase,"LOBBY","initial_phase")
check(state.epoch,0,"initial_epoch")
check(R.enroll(state,10),true,"enroll_10")
check(R.enroll(state,20),true,"enroll_20")
check(R.enroll(state,30),true,"enroll_30")
check(R.enroll(state,0),false,"no_fake_uid")
check(R.enroll(state,-1),false,"no_studio_negative_uid_without_server_mapping")
check(R.enroll(state,1.5),false,"fractional_uid")
local inv=R.export(state,10)
check(inv.owned.starter_scout,1,"starter_owned")
check(inv.discovered.starter_scout,true,"starter_discovered")
check(inv.equipped,"starter_scout","starter_equipped")
check(R.equip(state,10,"star_scout","MAGE"),false,"not_owned")
check(R.equip(state,10,"starter_scout","NINJA"),true,"starter_equip_legal")
check(R.equip(state,10,"starter_scout","ADMIN"),false,"unknown_class")
check(R.startRound(state,1),true,"first_round")
check(state.phase,"ACTIVE","round_active")
check(R.startRound(state,1),false,"duplicate_start")
check(R.equip(state,10,"starter_scout","WARRIOR"),false,"no_midround_equip")
check(R.finishRound(state,1,{[10]=true,[20]=true,[30]=false},{[10]=true}),true,"finish_once")
check(R.finishRound(state,1,{[10]=true},{[10]=true}),false,"round_finish_twice")
check(R.claimFreeHatch(state,30,1,1),false,"ineligible")
check(R.claimFreeHatch(state,10,2,1),false,"fake_epoch")
check(R.claimFreeHatch(state,10,1,0),false,"out_of_range_roll")
check(R.claimFreeHatch(state,10,1,10001),false,"over_roll")
check(R.claimFreeHatch(state,10,1,2.5),false,"fraction_roll")
local grantA,itemA,statusA=R.claimFreeHatch(state,10,1,500)
check(grantA,true,"server_grant_rare")
check(itemA,"star_scout","rare_500")
check(statusA,"GRANTED","receipt")
local grantB,itemB,statusB=R.claimFreeHatch(state,20,1,500)
check(grantB,true,"free_noncarrier_grant")
check(itemB,"forest_scout","normal_roll500")
check(statusB,"GRANTED","receipt20")
local replay,itemReplay,statusReplay=R.claimFreeHatch(state,10,1,9999)
check(replay,true,"idempotent_true")
check(itemReplay,"star_scout","idempotent_first_reward")
check(statusReplay,"ALREADY_GRANTED","idempotent_receipt")
inv=R.export(state,10)
check(inv.owned.star_scout,1,"rare_owned_once")
check(inv.receipts[1],"star_scout","receipt_epoch1")
check(inv.discovered.star_scout,true,"rare_discovered")
check(R.equip(state,10,"star_scout","BEASTMASTER"),true,"equip_owned")
check(R.equip(state,20,"star_scout","BEASTMASTER"),false,"unowned_rejected")
check(R.equip(state,10,"unknown","BEASTMASTER"),false,"unknown_item")
check(R.startRound(state,2),true,"second_round")
local success,token=R.requestScout(state,10,2,0)
check(success,true,"scout_next_round")
check(token.ability,"SCOUT","real_adapter_permission")
check(token.duration,5,"duration5")
check(token.cooldown,18,"cooldown18")
check(token.cosmetic,"star","rare_skin")
check(token.itemId,"star_scout","actual_equipped_item")
check(R.requestScout(state,10,2,0),false,"spam_0")
check(R.requestScout(state,10,2,5),false,"cooldown_at5")
check(R.requestScout(state,10,2,17),false,"cooldown_17")
check(R.requestScout(state,10,1,18),false,"stale_epoch")
check(R.requestScout(state,10,2,18),true,"ready_18")
check(R.requestScout(state,10,2,-1),false,"negative_clock")
check(R.requestScout(state,10,2,2.5),false,"fraction_clock")
local okForest,tokenForest=R.requestScout(state,20,2,0)
check(okForest,true,"starter_still_usable")
check(tokenForest.ability,"SCOUT","starter_same_tactical_effect")
check(tokenForest.duration,token.duration,"rare_not_longer")
check(tokenForest.cooldown,token.cooldown,"rare_not_faster")
check(R.requestScout(state,999,2,0),false,"ghost_not_enrolled")
check(R.finishRound(state,2,{[10]=true,[20]=true},{}),true,"finish2")
local saved=R.export(state,10)
local restored=R.new()
check(R.restore(restored,10,saved),true,"restore_data_contract")
local record=R.export(restored,10)
check(record.equipped,"star_scout","restore_equip")
check(record.owned.star_scout,1,"restore_owned")
check(record.receipts[1],"star_scout","restore_receipt")
local bad=R.new()
check(R.restore(bad,10,{owned={admin_dragon=1},receipts={}}),false,"reject_admin_save")
check(R.restore(bad,10,{owned={star_scout=-1},receipts={}}),false,"negative_owned")
check(R.restore(bad,10,{owned={star_scout=1},receipts={[-1]="star_scout"}}),false,"replayed_invalid_epoch")
check(R.restore(bad,10,{owned={},receipts={[1]="unknown"}}),false,"unknown_receipt")
check(R.restore(bad,10,{owned={},receipts={}}),true,"starter_only_valid")
check(R.export(bad,10).owned.starter_scout,1,"starter_never_missing")
local c=R.catalog()
check(c.star_scout.category,"BEAST","first_category_real")
check(c.star_scout.rarity,"RARE","rare_cosmetic")
for i=1,101 do
 check(R.claimFreeHatch(state,10,1,i),true,"repeat_hatch_still_only_one_"..tostring(i))
end
check(R.export(state,10).owned.star_scout,1,"replay_never_dup")
print("EGG_RUMBLE_ORIGINAL_FREE_HATCH_EQUIP_SCOUT_REAL_NATIVE_LUAU_PASS_"..tostring(tests))
'''
out=args.write
out.parent.mkdir(parents=True,exist_ok=True)
out.write_text(tests,encoding="utf-8")
print("Genuine original free hatch pure policy test input Git blob",blob)
