"""No-network Sourcery review signal tests. Never fake CI/provider verdicts."""
from __future__ import annotations
import importlib.util
from pathlib import Path
import unittest

SOURCE=Path(__file__).resolve().parents[1]/"tools/p0d_sourcery_intake.py"
spec=importlib.util.spec_from_file_location("p0d_sourcery_intake",SOURCE)
mod=importlib.util.module_from_spec(spec)
assert spec.loader is not None
spec.loader.exec_module(mod)
HEAD="a"*40
OLD="b"*40

def pr():
    return {"head":{"sha":HEAD},"number":314,"base":{"repo":{"full_name":"kk051780/toy-wars-factory"}}}
def item(body,author="sourcery-ai[bot]",commit=None):
    x={"id":10,"body":body,"user":{"login":author},"html_url":"https://github.com/kk051780/toy-wars-factory/pull/314#discussion_r10"}
    if commit:
        x.update({"commit_id":commit,"path":"server/Game.server.luau","line":44})
    return x
def check(conclusion,status="completed",sha=HEAD):
    return {"id":333,"name":"Sourcery review","head_sha":sha,"conclusion":conclusion,
            "status":status,"html_url":"https://github.com/kk051780/toy-wars-factory/runs/333"}
def scan(issue=None,inline=None,reviews=None,checks=None):
    return mod.evaluate(pr(),issue or [],inline or [],reviews or [],checks or [])

class SourceryIntake(unittest.TestCase):
    def test_guide_is_not_approval(self):
        r=scan(issue=[item("<!-- Generated by sourcery-ai[bot]: start review_guide -->\n## Reviewer's Guide\n### Tests")])
        self.assertEqual(r["verdict"],"GUIDE_ONLY_NOT_APPROVED")
        self.assertEqual(r["counts"]["guides"],1)
        self.assertEqual(r["counts"]["p0"],0)
    def test_real_check_success_still_needs_ci(self):
        r=scan(issue=[item("## Reviewer's Guide")],checks=[check("success")])
        self.assertEqual(r["verdict"],"SOURCERY_CHECK_GREEN_OTHER_QA_STILL_REQUIRED")
        self.assertFalse(r["authorizes_merge_or_rc_adoption"])
    def test_failed_check_is_p0(self):
        self.assertEqual(scan(checks=[check("failure")])["verdict"],"P0_SOURCERY_CHECK_FAILURE")
    def test_pending_not_success(self):
        self.assertEqual(scan(checks=[check(None,"in_progress")])["verdict"],"UNVERIFIED_SOURCERY_PENDING")
    def test_skipped_not_success(self):
        self.assertEqual(scan(checks=[check("skipped")])["verdict"],"UNVERIFIED_SOURCERY_SKIPPED")
    def test_high_security_inline(self):
        r=scan(inline=[item("🚨 issue (security): Critical exploit lets client inject reward",commit=HEAD)])
        self.assertEqual(r["counts"]["p0"],1)
        self.assertEqual(r["verdict"],"P0_REVIEW_REQUIRED")
    def test_score_issue_p1_safety(self):
        r=scan(inline=[item("issue (bug_risk): duplicate egg score is possible",commit=HEAD)])
        self.assertEqual(r["findings"][0]["priority"],"P1_SAFETY")
    def test_generic_issue_p1(self):
        r=scan(inline=[item("issue (bug_risk): this returns the wrong type",commit=HEAD)])
        self.assertEqual(r["verdict"],"P1_REVIEW_AND_FIX_OR_TRIAGE")
    def test_nitpick_backlog_no_rc_block(self):
        r=scan(inline=[item("nitpick (performance): avoid recomputing formatting",commit=HEAD)])
        self.assertEqual(r["verdict"],"P2_BACKLOG_ONLY")
    def test_old_commit_not_counted_as_active_or_resolved(self):
        r=scan(inline=[item("🚨 issue (security): Critical injection",commit=OLD)])
        self.assertEqual(r["counts"]["p0"],0)
        self.assertEqual(r["counts"]["old_commit_inline_resolution_unknown"],1)
        self.assertEqual(r["findings"][0]["resolution"],"UNKNOWN_REVIEW_THREAD_STATE")
    def test_only_actual_bot_counts(self):
        r=scan(inline=[item("🚨 issue (security): exploit",author="random-contributor",commit=HEAD)])
        self.assertEqual(r["verdict"],"NO_SOURCERY_EVIDENCE")
    def test_last_matching_head_check_wins(self):
        r=scan(checks=[check("failure",sha=OLD),check("success",sha=HEAD)])
        self.assertEqual(r["verdict"],"SOURCERY_CHECK_GREEN_OTHER_QA_STILL_REQUIRED")
    def test_missing_evidence_is_not_pass(self):
        self.assertEqual(scan()["verdict"],"NO_SOURCERY_EVIDENCE")
    def test_md_has_separate_guide_and_actionable(self):
        r=scan(issue=[item("## Reviewer's Guide")],
               inline=[item("issue (bug_risk): score can duplicate",commit=HEAD)])
        md=mod.markdown(r)
        self.assertIn("Guide",md)
        self.assertIn("P1_SAFETY",md)
        self.assertIn("source-exact Rojo",md)
    def test_wrong_sha_refuses_to_fake_result(self):
        p=pr()
        p["head"]["sha"]="not_real_head"
        with self.assertRaises(AssertionError):
            mod.evaluate(p,[],[],[],[])

if __name__=="__main__":
    unittest.main()
