-- Service-model regressions for the accepted canonical whole-server harness.
-- All original gameplay assertions remain in tests/server_event_spec.lua.
local H=dofile("tests/roblox_server_harness.lua")
local server=os.getenv("TWF_SERVER_FILE") or "src/ToyWarsServer.server.lua"
local passed,failed=0,0
local function eq(a,b,label)
    assert(a==b,(label or "value")..": expected "..tostring(b)..", got "..tostring(a))
end
local function check(name,fn)
    local ok,err=pcall(fn)
    if ok then passed=passed+1;print("PASS "..name)
    else failed=failed+1;print("FAIL "..name..": "..tostring(err)) end
end
check("default services allow real canonical server workshop admission",function()
    local h=H.new(server)
    local p=h:addPlayer(h:newPlayer())
    assert(p:FindFirstChild("leaderstats"),"normal gameplay must initialize")
    eq(h:mapCount(),1,"one workshop")
    h:removePlayer(p)
    eq(h:mapCount(),0,"workshop released")
end)
check("named stores and harnesses have isolated deterministic data",function()
    local a=H.new(server);local b=H.new(server)
    local s=a.services.DataStoreService:GetDataStore("test")
    eq(s,a.services.DataStoreService:GetDataStore("test"),"stable named store")
    s:UpdateAsync("key",function(current) eq(current,nil,"new key");return {coins=300} end)
    eq(s:GetAsync("key").coins,300,"saved value")
    eq(a.services.DataStoreService:GetDataStore("other"):GetAsync("key"),nil,"other name")
    eq(a.services.DataStoreService:GetDataStore("test","other"):GetAsync("key"),nil,"other scope")
    eq(b.services.DataStoreService:GetDataStore("test"):GetAsync("key"),nil,"other harness")
end)
check("read write and transform values cannot mutate stored data by alias",function()
    local h=H.new(server);local s=h.services.DataStoreService:GetDataStore("copy")
    local original={nested={coins=100}}
    local saved=s:UpdateAsync("key",function() return original end)
    original.nested.coins=200;saved.nested.coins=300
    eq(s:GetAsync("key").nested.coins,100,"write copies")
    local read=s:GetAsync("key");read.nested.coins=400
    s:UpdateAsync("key",function(current) current.nested.coins=500;return nil end)
    eq(s:GetAsync("key").nested.coins,100,"read and canceled transform copies")
end)
check("nil cancellation preserves value user IDs and metadata",function()
    local h=H.new(server);local s=h.services.DataStoreService:GetDataStore("cancel")
    s:UpdateAsync("key",function() return {coins=100},{123},{tag="keep"} end)
    eq(s:UpdateAsync("key",function(_,info)
        local ids=info:GetUserIds();ids[1]=999
        local meta=info:GetMetadata();meta.tag="changed"
        return nil
    end),nil,"canceled result")
    local current,info=s:GetAsync("key")
    eq(current.coins,100,"value retained")
    eq(info:GetUserIds()[1],123,"IDs retained")
    eq(info:GetMetadata().tag,"keep","metadata retained")
end)
check("successful transforms must explicitly preserve metadata associations",function()
    local h=H.new(server);local s=h.services.DataStoreService:GetDataStore("metadata")
    s:UpdateAsync("key",function() return {coins=100},{123},{tag="keep"} end)
    s:UpdateAsync("key",function(value,info)
        value.coins=200;return value,info:GetUserIds(),info:GetMetadata()
    end)
    local value,info=s:GetAsync("key")
    eq(value.coins,200,"new value");eq(info:GetUserIds()[1],123,"explicit IDs")
    eq(info:GetMetadata().tag,"keep","explicit metadata")
    s:UpdateAsync("key",function(current) return current end)
    local _,cleared=s:GetAsync("key")
    eq(next(cleared:GetUserIds()),nil,"omitted IDs cleared")
    eq(next(cleared:GetMetadata()),nil,"omitted metadata cleared")
end)
check("session GUIDs are unique across calls and server fixtures",function()
    local a=H.new(server);local b=H.new(server)
    local first=a.services.HttpService:GenerateGUID(false)
    local second=a.services.HttpService:GenerateGUID(false)
    local other=b.services.HttpService:GenerateGUID(false)
    eq(#first,36,"GUID shape")
    assert(first~=second and first~=other and second~=other,"tokens collide")
end)
check("false values and thrown transforms preserve the stored state",function()
    local h=H.new(server);local s=h.services.DataStoreService:GetDataStore("false")
    eq(s:UpdateAsync("key",function() return false end),false,"false write")
    eq(s:GetAsync("key"),false,"false read")
    local ok=pcall(function()
        s:UpdateAsync("key",function(current)
            eq(current,false,"false callback value");error("injected transform error")
        end)
    end)
    eq(ok,false,"error propagated")
    eq(s:GetAsync("key"),false,"failed update preserves false")
end)
print(string.format("HARNESS_DATASTORE_SUMMARY %d passed / %d failed; deterministic services, not Roblox DataStore",passed,failed))
if failed>0 then os.exit(1) end
