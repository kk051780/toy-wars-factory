-- Canonical whole-server Lua fixture only; NOT Roblox engine or mobile evidence.
local H=dofile("tests/roblox_server_harness.lua")
local path="src/ToyWarsServer.server.lua"
local okCount,badCount=0,0
local function check(name,fn)
    local ok,e=pcall(fn)
    if ok then okCount=okCount+1;print("PASS "..name)
    else badCount=badCount+1;print("FAIL "..name..": "..tostring(e)) end
end
local function fixture(options)
    local h=H.new(path,0,options)
    local p=h:addPlayer(h:newPlayer())
    local status=p:FindFirstChild("ToyWarsStatus")
    local mode=status and status:FindFirstChild("ProgressMode")
    return h,p,status,mode
end
local function preview(h,p,mode)
    assert(mode and mode.Value=="STUDIO_PREVIEW_UNSAVED")
    assert(p:FindFirstChild("leaderstats") and h:workshop(p))
end
check("Studio read failure admits visibly UNSAVED PvE",function()
    local h,p,_,mode=fixture({studio=true,storeReadFail=true})
    preview(h,p,mode);assert(h.storeUpdates==nil)
end)
check("Studio missing DataStore admits UNSAVED PvE",function()
    local h,p,_,mode=fixture({studio=true,storeOpenFail=true})
    preview(h,p,mode);assert(h.storeUpdates==nil)
end)
check("live server read failure still refuses gameplay",function()
    local h,p,status=fixture({studio=false,storeReadFail=true})
    assert(not status and not p:FindFirstChild("leaderstats") and h:mapCount()==0)
end)
check("live missing store still fails closed",function()
    local h,p,status=fixture({studio=false,storeOpenFail=true})
    assert(not status and not p:FindFirstChild("leaderstats") and h:mapCount()==0)
end)
check("Studio invalid profile schema never enters preview",function()
    local h=H.new(path,0,{studio=true})
    local ds=h.services.DataStoreService:GetDataStore("ToyWarsProgressV1")
    ds:UpdateAsync("p:1",function() return {version=2,coins=900} end)
    local p=h:addPlayer(h:newPlayer())
    assert(not p:FindFirstChild("ToyWarsStatus") and h:mapCount()==0)
end)
check("Studio CAS claim failure never enters preview",function()
    local h,p,status=fixture({studio=true,storeWriteFail=true})
    assert(not status and not p:FindFirstChild("leaderstats") and h:mapCount()==0)
end)
check("Studio healthy DataStore stays SAVED",function()
    local h,p,_,mode=fixture({studio=true})
    assert(mode and mode.Value=="SAVED" and h:workshop(p))
    assert((h.storeUpdates or 0)>0)
end)
check("production healthy DataStore stays SAVED",function()
    local h,p,_,mode=fixture({studio=false})
    assert(mode and mode.Value=="SAVED" and h:workshop(p))
end)
check("unsaved preview never writes on heartbeat or player exit",function()
    local h,p,_,mode=fixture({studio=true,storeReadFail=true})
    preview(h,p,mode)
    h.runService.Heartbeat:Fire(0.25)
    h:removePlayer(p)
    assert(h.storeUpdates==nil and h:mapCount()==0)
end)
check("Studio preview still runs authoritative toy selection and PvE state",function()
    local h,p,status,mode=fixture({studio=true,storeReadFail=true})
    preview(h,p,mode)
    assert(status:FindFirstChild("BaseHP").Value==100)
    assert(status:FindFirstChild("FactoryLevel").Value==1)
    h.remote.OnServerEvent:Fire(p,"tankuru")
    assert(status:FindFirstChild("SelectedToy").Value=="TANKURU")
end)
check("unsaved players still obey four-workshop cap and queue",function()
    local h=H.new(path,0,{studio=true,storeReadFail=true})
    local p={}
    for i=1,5 do
        p[i]=h:addPlayer(h:newPlayer())
        assert((h:workshop(p[i])~=nil)==(i<=4))
    end
    h:removePlayer(p[1])
    assert(h:workshop(p[5]) and h:mapCount()==4 and h.storeUpdates==nil)
end)
check("leaving and rejoining preview restores unsaved defaults",function()
    local h,p,_,mode=fixture({studio=true,storeReadFail=true})
    preview(h,p,mode)
    p:FindFirstChild("leaderstats"):FindFirstChild("Coins").Value=700
    h:removePlayer(p)
    local second=h:addPlayer(h:newPlayer())
    assert(second:FindFirstChild("leaderstats"):FindFirstChild("Coins").Value==50)
    assert(h.storeUpdates==nil)
end)
check("visible HUD declares preview cannot save progress",function()
    local f=assert(io.open("src/ToyWarsHUD.client.lua","r"))
    local ui=f:read("*a");f:close()
    assert(ui:find("StudioPreviewNotice",1,true))
    assert(ui:find("STUDIO PREVIEW - PROGRESS NOT SAVED",1,true))
    assert(ui:find('progressMode.Value=="STUDIO_PREVIEW_UNSAVED"',1,true))
end)
print(string.format("STUDIO_UNSAVED_PREVIEW_SUMMARY %d passed / %d failed; canonical Lua mocks only",okCount,badCount))
if badCount>0 then os.exit(1) end
