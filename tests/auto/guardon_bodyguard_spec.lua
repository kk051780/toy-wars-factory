-- Server-authoritative GUARDON bodyguard: actual canonical server under Lua mocks.
-- Tests enemy targeting, pursuit bounds, boss, cross-workshop isolation and negative control.
-- No Roblox Studio/rendering/mobile/multiplayer engine verification is implied.
local H=dofile("tests/roblox_server_harness.lua")
local server=os.getenv("TWF_SERVER_FILE") or "src/ToyWarsServer.server.lua"
local B=dofile("src/ToyWarsBalance.lua")
local passed,failed=0,0
local function up(fn,name)
    for i=1,80 do
        local k,v=debug.getupvalue(fn,i)
        if not k then break end
        if k==name then return v end
    end
    error("missing canonical upvalue "..name)
end
local function fixture(path)
    local h=H.new(path or server)
    local player=h:addPlayer(h:newPlayer())
    local heart=assert(h.runService.Heartbeat.listeners[1]).fn
    local simulate=up(heart,"simulate")
    local sessions=up(heart,"sessions")
    local add=up(simulate,"addEntity")
    local update=up(simulate,"updateEntity")
    local state=assert(sessions[player])
    state.productionTimer=100
    state.waveBreak=100
    local function entity(id,side,x,z)
        local e=assert(add(state,id,side))
        e.x=state.x+(x or 0)
        e.z=z or 0
        e.cooldown=0
        return e
    end
    return h,state,entity,update,sessions,add
end
local function check(name,fn)
    local ok,err=pcall(fn)
    if ok then passed=passed+1;print("PASS "..name)
    else failed=failed+1;print("FAIL "..name..": "..tostring(err)) end
end
check("living GUARDON shields a nearer PON from JUNK damage",function()
    local _,s,entity,update=fixture()
    local pon=entity("pon","ally",0,0)
    local guard=entity("guardon","ally",2,0)
    local junk=entity("junk","enemy",0,0)
    update(s,junk,0.3)
    assert(pon.health==40 and guard.health==102,"JUNK must strike the shield, not PON")
    assert(junk.cooldown>0,"real server combat cooldown applied")
end)
check("intercepted GUARDON health bar updates on actual hit",function()
    local _,s,entity,update=fixture()
    entity("pon","ally",0,0)
    local guard=entity("guardon","ally",2,0)
    local enemy=entity("junk","enemy",0,0)
    update(s,enemy,0.3)
    local bar=assert(guard.model:FindFirstChild("HealthBar"))
    assert(math.abs(bar.Size.X-3.2*102/108)<1e-7)
end)
check("ordinary PON still takes damage without a shield toy",function()
    local _,s,entity,update=fixture()
    local pon=entity("pon","ally",0,0)
    local enemy=entity("junk","enemy",0,0)
    update(s,enemy,0.3)
    assert(pon.health==34)
end)
check("shield cannot protect ally farther than eight studs away",function()
    local _,s,entity,update=fixture()
    local pon=entity("pon","ally",0,0)
    local guard=entity("guardon","ally",9,0)
    local enemy=entity("junk","enemy",0,0)
    update(s,enemy,0.3)
    assert(pon.health==34 and guard.health==108)
end)
check("shield never teleports threat to a distant guardian",function()
    local _,s,entity,update=fixture()
    local pon=entity("pon","ally",0,0)
    local guard=entity("guardon","ally",7,0)
    local enemy=entity("junk","enemy",-1,0)
    update(s,enemy,0.3)
    assert(pon.health==34 and guard.health==108,"attacker cannot chase distant guard")
end)
check("dead GUARDON does not protect allies",function()
    local _,s,entity,update=fixture()
    local pon=entity("pon","ally",0,0)
    local guard=entity("guardon","ally",2,0)
    guard.alive=false
    guard.health=0
    local enemy=entity("junk","enemy",0,0)
    update(s,enemy,0.3)
    assert(pon.health==34 and guard.health==0)
end)
check("nearest eligible GUARDON is selected among two shields",function()
    local _,s,entity,update=fixture()
    local pon=entity("pon","ally",0,0)
    local far=entity("guardon","ally",4,0)
    local near=entity("guardon","ally",2,0)
    local enemy=entity("junk","enemy",0,0)
    update(s,enemy,0.3)
    assert(pon.health==40 and far.health==108 and near.health==102)
end)
check("bodyguard also protects CUREBO support from JUNK",function()
    local _,s,entity,update=fixture()
    local curebo=entity("curebo","ally",0,0)
    local guard=entity("guardon","ally",2,0)
    local enemy=entity("junk","enemy",0,0)
    update(s,enemy,0.3)
    assert(curebo.health==56 and guard.health==102)
end)
check("JUNK CAPTAIN hits shield for boss damage, not fragile ally",function()
    local _,s,entity,update=fixture()
    s.wave.Value=50
    s.enemyTarget=B.waveSize(50)
    s.enemiesMade=s.enemyTarget-1
    local pon=entity("pon","ally",0,0)
    local guard=entity("guardon","ally",2,0)
    local captain=entity("junk","enemy",0,0)
    assert(captain.boss and captain.damage==18)
    update(s,captain,0.3)
    assert(pon.health==40 and guard.health==90)
end)
check("guard only protects members of the same factory session",function()
    local h,s,entity,update,sessions,add=fixture()
    local pon=entity("pon","ally",0,0)
    local other=h:addPlayer(h:newPlayer())
    local otherState=assert(sessions[other])
    local foreign=assert(add(otherState,"guardon","ally"))
    foreign.x=s.x+2
    foreign.z=0
    local enemy=entity("junk","enemy",0,0)
    update(s,enemy,0.3)
    assert(pon.health==34 and foreign.health==108)
end)
check("a friendly GUARDON still attacks JUNK with normal cooldown",function()
    local _,s,entity,update=fixture()
    local guard=entity("guardon","ally",0,0)
    local enemy=entity("junk","enemy",0,0)
    update(s,guard,0.3)
    assert(enemy.health==32 and guard.health==108)
    assert(guard.cooldown>0)
end)
check("negative control: disabling the intercept is detected",function()
    local f=assert(io.open(server,"rb"))
    local original=f:read("*a")
    f:close()
    local disabled,count=original:gsub('target,dist=guardonInterception%(state,e,target,dist%)','target,dist=target,dist')
    assert(count==1,"exactly one live server intercept call required")
    local tmp=os.tmpname()
    local out=assert(io.open(tmp,"wb"));out:write(disabled);out:close()
    local ok,err=pcall(function()
        local _,s,entity,update=fixture(tmp)
        local pon=entity("pon","ally",0,0)
        local guard=entity("guardon","ally",2,0)
        local junk=entity("junk","enemy",0,0)
        update(s,junk,0.3)
        assert(pon.health==34 and guard.health==108,
            "mutated old behavior must hit the unprotected nearest ally")
        local detected=pcall(function() assert(pon.health==40 and guard.health==102) end)
        assert(not detected,"the positive shield assertion accepted a disabled guard")
    end)
    os.remove(tmp)
    assert(ok,err)
end)
print(string.format("AUTO_GUARDON_BODYGUARD_SUMMARY %d passed / %d failed; whole server native Lua mocks, NOT Roblox engine",passed,failed))
if failed>0 then os.exit(1) end
