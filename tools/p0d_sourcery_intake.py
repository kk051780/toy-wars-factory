#!/usr/bin/env python3
"""Read-only, commit-scoped Sourcery triage. A review guide is not QA PASS.

No external Python dependencies, API writes, merges, approval or paid calls.
"""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import re
from urllib import request

BOT = {"sourcery-ai[bot]", "sourcery-ai"}
REPO_RE = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
SHA_RE = re.compile(r"^[a-fA-F0-9]{40}$")
KIND_RE = re.compile(r"^\s*(?:🚨\s*)?(issue|nitpick|suggestion|question)\s*\(([a-z0-9_ -]+)\)\s*:", re.I | re.M)
HIGH_RE = re.compile(r"\b(critical|high severity|high risk|vulnerability|security finding)\b", re.I)
SENSITIVE_RE = re.compile(r"\b(remoteevent|remote|datastore|updateasync|saved? data|permissions?|duplicate (?:score|reward|game|store)|score|rewards?|egg|paid|purchase|exploit|injection|authentication|cas lock|authorization)\b", re.I)
GUIDE_MARKER = "Generated by sourcery-ai[bot]: start review_guide"

def bot_comment(item: dict) -> bool:
    return str((item.get("user") or {}).get("login", "")).lower() in BOT

def classify_body(body: str) -> tuple[str, str]:
    if GUIDE_MARKER in body or body.lstrip().startswith("## Reviewer's Guide"):
        return "INFO", "review_guide"
    m = KIND_RE.search(body)
    if "🚨" in body or (HIGH_RE.search(body) and "security" in body.lower()):
        return "P0", "critical_or_security"
    if m:
        k,area = m.group(1).lower(), m.group(2).lower()
        if k == "issue" and HIGH_RE.search(body):
            return "P0", area
        if k == "issue":
            return ("P1_SAFETY" if SENSITIVE_RE.search(body) else "P1"), area
        return "P2", area
    return "INFO", "general_note"

def extract(item: dict, channel: str, head: str) -> dict | None:
    if not bot_comment(item):
        return None
    body = str(item.get("body") or "")
    priority, kind = classify_body(body)
    commit = item.get("commit_id") if channel == "inline" else None
    return {
        "id": item.get("id"), "kind": "guide" if kind=="review_guide" else channel,
        "priority": priority, "type": kind, "url": item.get("html_url"),
        "path": item.get("path") if channel == "inline" else None,
        "line": item.get("line") if channel == "inline" else None,
        "commit_id": commit, "stale_commit": bool(commit and commit != head),
        "excerpt": re.sub(r"\s+", " ", body)[:240],
        "resolution": "UNKNOWN_REVIEW_THREAD_STATE" if channel == "inline" else "NOT_APPLICABLE"
    }

def pick_status(checks: list, head: str) -> dict:
    found = [x for x in checks if x.get("name")=="Sourcery review" and
             (not x.get("head_sha") or x["head_sha"]==head)]
    if not found:
        return {"status":"MISSING","conclusion":None,"url":None}
    c = max(found, key=lambda z: int(z.get("id") or 0))
    return {
        "status":str(c.get("status") or "UNKNOWN").upper(),
        "conclusion":str(c["conclusion"]).upper() if c.get("conclusion") else None,
        "url":c.get("html_url") or c.get("details_url")
    }

def evaluate(pr: dict, issue_comments: list, inline_comments: list,
             reviews: list, checks: list) -> dict:
    head = str((pr.get("head") or {}).get("sha") or "")
    assert SHA_RE.fullmatch(head), "EXACT_HEAD_REQUIRED"
    items = []
    for channel,rows in (("issue",issue_comments),("inline",inline_comments),("review",reviews)):
        for x in rows:
            if channel == "review" and not x.get("body"):
                continue
            finding = extract(x,channel,head)
            if finding:
                items.append(finding)
    status = pick_status(checks,head)
    active = [x for x in items if not x["stale_commit"]]
    high = [x for x in active if x["priority"]=="P0"]
    issues = [x for x in active if x["priority"] in ("P1","P1_SAFETY")]
    minor = [x for x in active if x["priority"]=="P2"]
    guides = [x for x in items if x["kind"]=="guide"]
    stale = [x for x in items if x["stale_commit"]]
    if status["conclusion"]=="FAILURE":
        verdict="P0_SOURCERY_CHECK_FAILURE"
    elif high:
        verdict="P0_REVIEW_REQUIRED"
    elif issues:
        verdict="P1_REVIEW_AND_FIX_OR_TRIAGE"
    elif status["conclusion"] in ("SKIPPED","CANCELLED","TIMED_OUT"):
        verdict="UNVERIFIED_SOURCERY_SKIPPED"
    elif status["status"] in ("IN_PROGRESS","QUEUED","REQUESTED","PENDING"):
        verdict="UNVERIFIED_SOURCERY_PENDING"
    elif minor:
        verdict="P2_BACKLOG_ONLY"
    elif status["conclusion"]=="SUCCESS":
        verdict="SOURCERY_CHECK_GREEN_OTHER_QA_STILL_REQUIRED"
    elif guides:
        verdict="GUIDE_ONLY_NOT_APPROVED"
    else:
        verdict="NO_SOURCERY_EVIDENCE"
    return {
        "schema":"P0D_SOURCERY_INTAKE_V1",
        "repo":(pr.get("base") or {}).get("repo",{}).get("full_name"),
        "pr_number":pr.get("number"),"head_sha":head,
        "sourcery_check":status,"verdict":verdict,
        "counts":{
            "guides":len(guides),"p0":len(high),"p1":len(issues),
            "p2":len(minor),"old_commit_inline_resolution_unknown":len(stale),
            "total_sourcery_items":len(items)},
        "findings":items,
        "authorizes_merge_or_rc_adoption":False,
        "separate_native_rojo_studio_required":True,
        "note":"Guides are not source PASS; old commit comments are not automatically resolved."
    }

def get(repo: str, endpoint: str, token: str) -> object:
    if not REPO_RE.fullmatch(repo):
        raise ValueError("INVALID_REPOSITORY")
    headers = {
        "Accept":"application/vnd.github+json",
        "X-GitHub-Api-Version":"2022-11-28",
        "User-Agent":"P0D-Sourcery-Read-Only"
    }
    if token:
        headers["Authorization"]="Bearer "+token
    req=request.Request("https://api.github.com/repos/"+repo+endpoint,headers=headers)
    with request.urlopen(req,timeout=25) as response:
        return json.load(response)

def collect(repo: str, number: int, token: str) -> dict:
    assert 0 < number < 1000000
    pr=get(repo,f"/pulls/{number}",token)
    head=pr["head"]["sha"]
    issues=get(repo,f"/issues/{number}/comments?per_page=100",token)
    inline=get(repo,f"/pulls/{number}/comments?per_page=100",token)
    reviews=get(repo,f"/pulls/{number}/reviews?per_page=100",token)
    checks=get(repo,f"/commits/{head}/check-runs?per_page=100",token)
    assert all(isinstance(x,list) for x in (issues,inline,reviews))
    report=evaluate(pr,issues,inline,reviews,checks.get("check_runs",[]))
    report["repo"]=repo
    report["data_limit"]="FIRST_100_EACH_ENDPOINT"
    return report

def markdown(report:dict)->str:
    c=report["counts"]
    s=report["sourcery_check"]
    lines=[
        "# P0D Sourcery read-only reviewer intake",
        "",
        "- PR #{n}, HEAD {sha}".format(n=report["pr_number"],sha=report["head_sha"]),
        "- Check: {st}, conclusion: {cl}".format(st=s["status"],cl=s["conclusion"]),
        "- Verdict: **{v}**".format(v=report["verdict"]),
        "- Guides (NOT a PASS): {n}".format(n=c["guides"]),
        "- P0/P1/P2: {a}/{b}/{d}".format(a=c["p0"],b=c["p1"],d=c["p2"]),
        "- Old commit comment resolution UNKNOWN: {n}".format(n=c["old_commit_inline_resolution_unknown"]),
        "",
        "| Priority | File | URL | Excerpt |",
        "|---|---|---|---|"
    ]
    for item in report["findings"]:
        if item["kind"]=="guide":
            continue
        excerpt=item["excerpt"].replace("|",r"\|").replace(chr(96),"'")
        lines.append("| {p} | {file} | {url} | {e} |".format(
            p=item["priority"]+(" (old commit)" if item["stale_commit"] else ""),
            file=item["path"] or "-",url=item["url"] or "-",e=excerpt))
    lines += ["","No auto-approval/merge/canonical RC adoption. Preserve 1 Game/Remote/Store.",
              "Sourcery is separate from native Luau, source-exact Rojo, Studio, Android and FUN.",""]
    return "\n".join(lines)

def main()->int:
    p=argparse.ArgumentParser()
    p.add_argument("--repo",default=os.environ.get("GITHUB_REPOSITORY",""))
    p.add_argument("--pr",type=int,default=0)
    p.add_argument("--fixture",type=Path)
    p.add_argument("--json",type=Path,required=True)
    p.add_argument("--md",type=Path,required=True)
    opts=p.parse_args()
    if opts.fixture:
        f=json.loads(opts.fixture.read_text(encoding="utf8"))
        report=evaluate(f["pr"],f["issue_comments"],f["inline_comments"],f["reviews"],f["checks"])
    elif opts.pr:
        report=collect(opts.repo,opts.pr,os.environ.get("GITHUB_TOKEN",""))
    else:
        report={
            "schema":"P0D_SOURCERY_INTAKE_V1","repo":opts.repo,"pr_number":None,
            "head_sha":os.environ.get("GITHUB_SHA","N/A"),
            "sourcery_check":{"status":"NOT_A_PR","conclusion":None,"url":None},
            "verdict":"NO_PR_CONTEXT_TESTS_ONLY",
            "counts":{"guides":0,"p0":0,"p1":0,"p2":0,"old_commit_inline_resolution_unknown":0,
                      "total_sourcery_items":0},
            "findings":[],"authorizes_merge_or_rc_adoption":False,
        }
    opts.json.parent.mkdir(parents=True,exist_ok=True)
    opts.json.write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf8")
    opts.md.parent.mkdir(parents=True,exist_ok=True)
    opts.md.write_text(markdown(report),encoding="utf8")
    print("P0D_SOURCERY_QA_TRIAGE",report["verdict"],json.dumps(report["counts"]))
    return 0

if __name__=="__main__":
    raise SystemExit(main())
